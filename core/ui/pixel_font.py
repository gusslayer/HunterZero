class PixelFont:
    """Render text from stored bitmaps with one square block per glyph pixel."""

    def __init__(self, scale: int) -> None:
        """Set how many physical pixels each glyph pixel occupies."""
        if scale <= 0:
            raise ValueError("La escala de la fuente debe ser positiva.")
        self.scale = scale
        self._glyph_cache: dict[tuple[str, tuple[int, int, int]], pygame.Surface] = {}

    def get_height(self) -> int:
        """Return the cell height in physical pixels."""
        return 8 * self.scale

    def get_linesize(self) -> int:
        """Return the vertical advance for text drawn on successive lines."""
        return 8 * self.scale

    def size(self, text: str) -> tuple[int, int]:
        """Return the width and height of a rendered string."""
        return len(text) * 8 * self.scale, self.get_height()

    def render(self, text: str, antialias: bool = False, color=(255, 255, 255)) -> pygame.Surface:
        """Compose a string from cached glyph bitmaps, ignoring any antialias flag."""
        del antialias
        width, height = self.size(text)
        surface = pygame.Surface((width, height), pygame.SRCALPHA)
        for index, character in enumerate(text.upper()):
            glyph = self._glyph(character, color)
            if glyph is not None:
                surface.blit(glyph, (index * 8 * self.scale, 0))
        return surface

    def _glyph(self, character: str, color) -> pygame.Surface | None:
        """Return the cached bitmap for one character, or None for an empty glyph."""
        key = (character, color)
        cached = self._glyph_cache.get(key)
        if cached is not None:
            return cached
        rows = _GLYPHS.get(character, _GLYPHS["?"])
        glyph = pygame.Surface((8 * self.scale, 8 * self.scale), pygame.SRCALPHA)
        for y, row in enumerate(rows):
            for x, bit in enumerate(row):
                if bit == "1":
                    pygame.draw.rect(
                        glyph,
                        color,
                        (x * self.scale, y * self.scale, self.scale, self.scale),
                    )
        self._glyph_cache[key] = glyph
        return glyph
